/** Read-only verification of the corrected body-level glow on the Docker UI. */
import {chromium} from '../frontend/dashboard/node_modules/playwright/index.mjs';
import {strict as assert} from 'node:assert';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--ignore-gpu-blocklist']});
const evidence={at:new Date().toISOString(),checks:[],errors:[],posts:[]};
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 page.on('pageerror',e=>evidence.errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')evidence.errors.push(m.text());});
 page.on('request',r=>{if(r.method()==='POST')evidence.posts.push(r.url());});
 const journals={};
 for(const id of ['DEMO-001','DEMO-002'])journals[id]=await (await page.request.get(`http://localhost:8080/api/patients/${id}/journal`)).json();
 await page.goto('http://localhost:3000/?patient=DEMO-001#overview');
 const hero=page.getByTestId('landing-experience');
 await hero.waitFor({state:'visible'});
 await page.waitForFunction(()=>document.querySelector('[data-testid=landing-experience]')?.dataset.sceneStatus==='ready');
 assert.equal(await hero.getAttribute('data-organ-palette'),'natural');
 assert.equal(await hero.getAttribute('data-body-framing'),'neck-to-knees');
 assert.equal(await hero.getAttribute('data-body-tone'),'steady');
 const canvas=hero.locator('#scene canvas');
 await canvas.screenshot({path:'D:/3Nov/docs/screenshots/body_aura_green.png',style:'.site-header,.app-header{visibility:hidden!important}'});
 await hero.getByRole('button',{name:'Scripted curve',exact:true}).click();
 const slider=hero.getByRole('slider',{name:'Select sample reading'});
 await slider.fill('4');assert.equal(await hero.getAttribute('data-body-tone'),'attention');
 await canvas.screenshot({path:'D:/3Nov/docs/screenshots/body_aura_red.png'});
 await hero.getByRole('button',{name:'Fictional day',exact:true}).click();
 await slider.fill('0');assert.equal(await hero.getAttribute('data-body-tone'),'neutral');
 assert.equal(await hero.getAttribute('data-body-glow'),'#629cf5');
 await canvas.screenshot({path:'D:/3Nov/docs/screenshots/body_aura_blue.png'});
 await slider.fill('5');assert.equal(await hero.getAttribute('data-body-tone'),'off');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await slider.fill('8');await slider.fill('0');await slider.fill('8');
 await page.waitForTimeout(650);
 assert.equal(await hero.getAttribute('data-body-tone'),'steady');
 await page.emulateMedia({reducedMotion:'reduce'});
 await hero.locator('[data-organ-hotspot=pancreas]').click();
 await page.waitForFunction(()=>document.querySelector('[data-testid=landing-experience]')?.dataset.focusState==='ready');
 assert.equal(await hero.locator('#organ-info-title').innerText(),'Pancreas');
 await hero.locator('#back-to-body').click();
 await page.setViewportSize({width:400,height:900});
 await canvas.screenshot({path:'D:/3Nov/docs/screenshots/body_aura_mobile.png'});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 evidence.checks.push('Landing: green/red/blue/off, rapid retarget, reduced motion, natural palette, neck-to-knees geometry, organ focus and narrow layout.');
 await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Patient workspace',exact:true}).click();
 const ws=page.locator('[data-destination=workspace]'),demo=ws.locator('.workspace-scenarios');
 await demo.locator(':scope>summary').click();
 await page.waitForFunction(()=>document.querySelector('[data-instance=workspace-demo] [data-testid=anatomy-stage]')?.getAttribute('data-status')==='ready');
 const stage=demo.getByTestId('anatomy-stage');
 assert.equal(await stage.getAttribute('data-organ-palette'),'natural');
 assert.equal(await stage.getAttribute('data-body-framing'),'neck-to-knees');
 await demo.getByLabel('Fictional glucose story').selectOption('countdown');
 assert.equal(await demo.getByTestId('projection-clock').innerText(),'42:00');
 assert.equal(await stage.getAttribute('data-body-tone'),'steady');
 await demo.getByLabel('3D sample',{exact:true}).fill('4');
 assert.equal(await stage.getAttribute('data-body-tone'),'attention');
 await stage.screenshot({path:'D:/3Nov/docs/screenshots/workspace_body_aura.png'});
 await demo.getByRole('checkbox',{name:'Show glucose overlay'}).uncheck();
 assert.equal(await stage.getAttribute('data-body-tone'),'off');
 evidence.checks.push('Workspace: shared aura/crop, sample-linked color, 42-minute projection, overlay off.');
 for(const id of Object.keys(journals))assert.deepEqual(await (await page.request.get(`http://localhost:8080/api/patients/${id}/journal`)).json(),journals[id]);
 assert.deepEqual(evidence.errors,[]);assert.deepEqual(evidence.posts,[]);
 evidence.checks.push('No browser or shader errors, no POSTs and both saved journals unchanged.');
 fs.writeFileSync('D:/3Nov/docs/research/body_aura_live_2026-11-03.json',JSON.stringify(evidence,null,2));
 console.log(JSON.stringify(evidence,null,2));
} finally {await browser.close();}
