 await panel.getByRole('button',{name:'Pause projection clock'}).click();
 await panel.getByRole('button',{name:'Reset projection clock'}).click();
 assert.equal(await panel.getByTestId('projection-clock').innerText(),'42:00');
 await page.screenshot({path:'D:/3Nov/docs/screenshots/visual_twin_live_projection_desktop.png'});
 evidence.checks.push('42-minute fictional arithmetic, explicit ticking, pause and reset work on production.');
