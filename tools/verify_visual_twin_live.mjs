 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'D:/3Nov/docs/screenshots/visual_twin_live_projection_mobile.png'});
 await future.getByRole('link',{name:'Validation roadmap'}).click();
 assert.equal(await nav.getByRole('link',{name:'Evidence',exact:true}).getAttribute('aria-current'),'page');
