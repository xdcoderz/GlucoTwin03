 const slide=await page.request.get('http://localhost:3000/research/glucotwin_validation_roadmap.pptx');
 assert.equal(slide.status(),200);assert.equal((await slide.body()).subarray(0,2).toString(),'PK');
 evidence.checks.push('400px view, roadmap deep link and actual PowerPoint download work.');
