 await workspace.getByTestId('anatomy-stage').scrollIntoViewIfNeeded();
 await page.screenshot({path:'D:/3Nov/docs/screenshots/visual_twin_live_body.png'});
 evidence.checks.push('Actual saved model score drives a separate base arc; medication context toggles its own outline.');
 const nav=page.getByRole('navigation',{name:'Main navigation'});
