import { chromium } from '../frontend/dashboard/node_modules/playwright/index.mjs';
import { strict as assert } from 'node:assert';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--ignore-gpu-blocklist']});
const evidence={checkedAt:new Date().toISOString(),mode:'real production container, existing saved scores, read-only',checks:[],postRequests:[],errors:[]};
