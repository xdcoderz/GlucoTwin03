 assert.equal(await panel.getAttribute('data-state'),'flagged');
 await future.getByLabel('3D sample',{exact:true}).fill('4');
 assert.equal(await future.getByTestId('pattern-panel').getAttribute('data-kind'),'reversal');
 evidence.checks.push('Scripted jump and reversal trigger labelled rules and withhold countdown.');
 await future.getByRole('button',{name:'Open falling trend demo'}).click();
