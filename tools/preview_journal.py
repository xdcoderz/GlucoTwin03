"""In-memory synthetic workflow adapter. No model, clinical use or durable storage."""
import copy
import hashlib
import json
import uuid
from datetime import datetime, timedelta, timezone
from pathlib import Path

FUTURE = json.loads((Path(__file__).resolve().parents[1] / 'backend/fusion-api/src/main/resources/follow_up_synthetic.json').read_text())['patients']


def initialize(server):
    if not hasattr(server, 'journal'):
        server.journal = {pid: [] for pid in server.patients}
        server.followup = {pid: {} for pid in server.patients}


def view(server, pid, record=None):
    initialize(server)
    data = server.patients[pid]
    baseline = datetime.fromisoformat(data['currentMeal']['baselineAt'].replace('Z', '+00:00'))
    base = data['cgmHistory'][-1]['glucoseMgDl'] if data['cgmHistory'] else None
    future = list(server.followup[pid].values())
    future.sort(key=lambda row: row['observedAt'])
    count = len(future)
    maximum = max((r['glucoseMgDl'] for r in future), default=None)
    rise = maximum - base if maximum is not None and base is not None else None
    complete = count == 8
    high, rising = maximum is not None and maximum >= 180, rise is not None and rise >= 40
    event = True if high or rising else False if complete else None
    status = 'event_observed' if event else 'no_event_observed_complete' if complete else 'insufficient_follow_up' if 120 in server.followup[pid] else 'partial_follow_up' if count else 'awaiting_outcome'
    result = copy.deepcopy(record) if record else {
        'predictionId': None, 'patientId': pid, 'displayName': data['patient']['displayName'],
        'mealId': data['currentMeal']['mealId'], 'baselineAt': data['currentMeal']['baselineAt'],
        'computedAt': None, 'horizonEnd': (baseline + timedelta(minutes=120)).isoformat(),
        'clockMode': 'synthetic_replay', 'inputHash': hashlib.sha256(json.dumps(data, sort_keys=True).encode()).hexdigest(),
        'prospective': False, 'superseded': False, 'inputChanged': False,
        'baselineGlucoseMgDl': base, 'baselineAlreadyHigh': base is not None and base >= 180,
        'qualityIssues': [], 'prediction': copy.deepcopy(data['prediction']), 'snapshot': copy.deepcopy(data),
        'reviewState': 'awaiting_review', 'reviews': [],
    }
    result['superseded'] = bool(record and server.journal[pid][0]['predictionId'] != record['predictionId'])
    result['outcome'] = {'status': status, 'expectedSamples': 8, 'receivedSamples': count, 'complete': complete,
        'conflictingTimestamps': 0, 'eventObserved': event, 'reaches180': True if high else False if complete else None,
        'rises40': True if rising else False if complete else None, 'observedMaxMgDl': maximum, 'observedRiseMgDl': rise,
        'predictionMatched': None, 'readings': future,
        'note': 'Fictional synthetic follow-up; not generated by a model. Eight 15-minute samples are not continuous coverage. Preview journal is memory-only; Spring/H2 provides durable records.'}
    return result


def latest(server, pid):
    initialize(server)
    return view(server, pid, server.journal[pid][0] if server.journal[pid] else None)


def readiness(server, pid):
    """Preview-only adapter: always reports the model unavailable, never probes/invents it."""
    data = server.patients[pid]
    current = latest(server, pid)
    baseline = datetime.fromisoformat(data['currentMeal']['baselineAt'].replace('Z', '+00:00'))
    slots, issues = [], []
    for minute in range(120, -1, -15):
        at = baseline - timedelta(minutes=minute)
        values = {r['glucoseMgDl'] for r in data['cgmHistory'] if datetime.fromisoformat(r['observedAt'].replace('Z', '+00:00')) == at}
        status = 'missing' if not values else 'received' if len(values) == 1 else 'conflict'
        if status != 'received': issues.append(f'{status}_history_offset_{minute}')
        slots.append({'minutesBefore': minute, 'observedAt': at.isoformat(), 'status': status, 'glucoseMgDl': next(iter(values)) if status == 'received' else None})
    now = datetime.now(timezone.utc).isoformat()
    return {'patientId': pid, 'serverTime': now, 'baselineAt': baseline.isoformat(), 'clockMode': 'synthetic_replay',
        'historyReady': not issues, 'receivedExpectedSamples': sum(s['status'] == 'received' for s in slots), 'expectedSamples': 9,
        'historySlots': slots, 'qualityIssues': issues, 'latestReceivedAt': None,
        'model': {'status': 'unavailable', 'modelVersion': None, 'checkedAt': now},
        'predictionId': current['predictionId'], 'predictionStatus': current['prediction']['status'], 'computedAt': current['computedAt'],
        'inputChanged': current['inputChanged'], 'followUpSamples': current['outcome']['receivedSamples'],
        'followUpComplete': current['outcome']['complete'], 'reviewState': current['reviewState'], 'nextAction': 'history' if issues else 'score'}


def save(server, pid):
    record = view(server, pid)
    record['predictionId'] = str(uuid.uuid4())
    record['computedAt'] = datetime.now(timezone.utc).isoformat()
    record['prospective'] = not bool(server.followup[pid])
    server.journal[pid].insert(0, record)
    return record['prediction']


def find(server, prediction_id):
    initialize(server)
    return next(((pid, r) for pid, records in server.journal.items() for r in records if r['predictionId'] == prediction_id), None)


def replay_future(server, pid, stage):
    initialize(server)
    baseline = datetime.fromisoformat(server.patients[pid]['currentMeal']['baselineAt'].replace('Z', '+00:00'))
    accepted = duplicates = 0
    for index, value in enumerate(FUTURE[pid]):
        minute = (index + 1) * 15
        if stage == 'partial' and minute > 45 or stage == 'gap' and minute == 60:
            continue
        if minute in server.followup[pid]:
            duplicates += 1
        else:
            accepted += 1
            server.followup[pid][minute] = {'patientId': pid, 'eventId': server.patients[pid]['currentMeal']['mealId'] + '-FOLLOWUP-' + str(minute),
                'observedAt': (baseline + timedelta(minutes=minute)).isoformat(), 'glucoseMgDl': value, 'source': 'synthetic-follow-up-replay'}
    return {'synthetic': True, 'stage': stage, 'accepted': accepted, 'duplicates': duplicates, 'modelScored': False}
