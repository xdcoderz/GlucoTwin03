import { openDisclosure } from './workspaceSupport';
import { test, expect } from './fixtures';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';

test('save, partial/gapped/complete follow-up, review, historical version and bound PDF', async ({ page, request }) => {
  test.setTimeout(75_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/worklist', async route => { await new Promise(done => setTimeout(done, 1500)); await route.continue(); });
  await page.goto('/#workspace');
  const workflow = page.getByRole('region', { name: 'Follow-up' });
  await expect(workflow.getByText('Loading saved research records…', { exact: true })).toBeVisible();
  await workflow.screenshot({ path: '../../docs/screenshots/workflow_loading.png' });
  await openDisclosure(page,'.patient-list');
  await expect(workflow.getByRole('button', { name: 'DEMO-001', exact: true })).toBeVisible();
  await page.unroute('**/api/worklist');
  await expect(workflow).toContainText('Already ≥180 at baseline');
  await expect(workflow).toContainText('No scoring attempts saved');
  await workflow.screenshot({ path: '../../docs/screenshots/workflow_empty.png' });
  await page.getByRole('button', { name: /Score & save/ }).click();
  await expect(workflow.locator('.record-id')).toContainText('Result');
  const first = (await (await request.get('http://127.0.0.1:18083/api/patients/DEMO-001/journal')).json())[0];
  expect(first.prediction.model_score).toBeNull();
  expect(first.prospective).toBe(true);
  await openDisclosure(page,'.demo-controls');
  await workflow.getByRole('button', { name: 'Replay first 45 minutes' }).click();
  await expect(workflow.locator('.outcome-summary')).toContainText('3 of 8');
  await expect(workflow.locator('.outcome-summary')).toContainText('Partial follow-up');
  await openDisclosure(page,'.outcome-details');
  await expect(workflow.locator('.outcome-details')).toContainText('Reached 180: Unknown');
  await workflow.getByRole('button', { name: 'Replay with a missing sample' }).click();
  await expect(workflow.locator('.outcome-summary')).toContainText('7 of 8');
  await expect(workflow.locator('.outcome-summary')).toContainText('Incomplete follow-up');
  await workflow.getByRole('button', { name: 'Complete follow-up replay' }).click();
  await expect(workflow.locator('.outcome-summary')).toContainText('8 of 8');
  await expect(workflow.locator('.outcome-summary')).toContainText('No event observed in complete samples');
  // Follow-up samples must never change the saved meal-time baseline.
  await expect(page.locator('.meal-context-meta')).toContainText('142 mg/dL');
  await workflow.getByLabel('Local demo review note').fill('TEST ONLY: reviewed the fictional meal response; all sample times present.');
  await workflow.getByRole('button', { name: 'Mark reviewed', exact: true }).click();
  await openDisclosure(page,'.review-history-disclosure');
  await expect(workflow.getByRole('list', { name: 'Review history' })).toContainText('TEST ONLY');
  const download = page.waitForEvent('download');
  await workflow.getByRole('button', { name: 'Download saved result' }).click();
  const file = resolve('../../output/pdf/glucotwin_journal_example.pdf');
  await (await download).saveAs(file);
  const text = execFileSync('python', ['-c', 'import sys; from pypdf import PdfReader; print("\\n".join(p.extract_text() for p in PdfReader(sys.argv[1]).pages))', file], { encoding: 'utf8' });
  expect(text).toContain(first.predictionId);
  expect(text).toContain('Input SHA-256');
  expect(text).toContain('8/8 expected sample times');
  expect(text).toContain('TEST ONLY: reviewed');
  expect(text).toContain('NOT AVAILABLE - no score substituted');
  expect(text).not.toContain('no saved inference timestamp');
  await workflow.screenshot({ path: '../../docs/screenshots/workflow_journal_desktop.png' });
  await page.reload();
  await openDisclosure(page,'.review-history-disclosure');
  await expect(workflow.getByRole('list', { name: 'Review history' })).toContainText('TEST ONLY');
  await page.getByRole('button', { name: /Score & save/ }).click();
  await expect(workflow.locator('.workflow-caution')).toContainText('Retrospective record');
  await openDisclosure(page,'.saved-attempts');
  await expect(workflow.getByRole('complementary', { name: 'Saved prediction versions' }).getByRole('button')).toHaveCount(2);
  await workflow.getByRole('button', { name: /Earlier attempt/ }).click();
  await expect(workflow.locator('.record-id')).toContainText(first.predictionId);
  await expect(workflow).toContainText('Historical saved result');
  await workflow.getByLabel('Local demo review note').fill('TEST ONLY: reopened for discussion.');
  await workflow.getByRole('button', { name: 'Reopen review' }).click();
  await openDisclosure(page,'.review-history-disclosure');
  await expect(workflow.getByRole('list', { name: 'Review history' })).toContainText('Reopened');
  await openDisclosure(page,'.patient-list');
  await workflow.getByRole('button', { name: 'DEMO-002', exact: true }).click();
  await expect(page.getByLabel('Synthetic scenario')).toHaveValue('DEMO-002');
  await expect(workflow).toContainText('No scoring attempts saved');
  await page.getByRole('button', { name: /Score & save/ }).click();
  await openDisclosure(page,'.demo-controls');
  await workflow.getByRole('button', { name: 'Replay first 45 minutes' }).click();
  await expect(workflow.locator('.outcome-summary')).toContainText('Event observed in samples');
  await expect(workflow.locator('.outcome-details')).toContainText('Prediction agreement: Not assessed');
  expect(errors).toEqual([]);
});

test('mobile keyboard review and workflow dependency failure/recovery', async ({ page, request }) => {
  // This test must also run by itself, without records left by another test.
  await request.post('http://127.0.0.1:18083/api/patients/DEMO-001/refresh');
  await page.setViewportSize({ width: 400, height: 860 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/#workspace');
  const workflow = page.getByRole('region', { name: 'Follow-up' });
  await openDisclosure(page,'.journal-technical');
  await expect(workflow.locator('.record-id')).toBeVisible();
  const longNote = ('TEST ONLY: keyboard review on narrow screen. ' + 'Synthetic review context with a long note. '.repeat(50)).slice(0, 1000);
  await workflow.getByLabel('Local demo review note').fill(longNote);
  await workflow.getByRole('button', { name: 'Mark reviewed', exact: true }).focus();
  await page.keyboard.press('Enter');
  await openDisclosure(page,'.review-history-disclosure');
  await expect(workflow.getByRole('list', { name: 'Review history' })).toContainText('keyboard review');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await workflow.screenshot({ path: '../../docs/screenshots/workflow_journal_mobile.png' });
  await page.route('**/api/worklist', route => route.fulfill({ status: 503, json: { error: 'TEST ONLY offline worklist' } }));
  await page.reload();
  await expect(page.getByRole('button', { name: 'Retry worklist' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Save scoring attempt' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: /Score & save/ })).toBeEnabled();
  await page.getByRole('region', { name: 'Follow-up' }).screenshot({ path: '../../docs/screenshots/workflow_error_mobile.png' });
  await page.unroute('**/api/worklist');
  await page.getByRole('button', { name: 'Retry worklist' }).click();
  await expect(page.getByRole('button', { name: /Score & save/ })).toBeEnabled();
  await openDisclosure(page,'.journal-technical');
  await expect(page.locator('.record-id')).toBeVisible();
});
