test('patient cockpit, closed tools and one timeline shared with the optional twin',async({page,request})=>{
  test.setTimeout(60000);
  const seeded=await request.post('http://127.0.0.1:18083/api/patients/DEMO-001/refresh');
  expect(seeded.ok()).toBe(true);
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'reduce'});await page.goto('/#workspace');
  const ws=page.locator('[data-destination=workspace]');
  await expect(ws.locator('.review-form')).toBeVisible({timeout:15000});
  await expect(ws.getByRole('navigation',{name:'Dashboard sections'}).getByRole('link')).toHaveText(['01Patient & meal','02Glucose history','03Score & factors','04Follow-up','05Review']);
  for(const selector of ['#patient-twin','.replay-forecast','.saved-attempts','.journal-technical','.demo-controls','.readiness-technical'])await expect(ws.locator(selector)).not.toHaveAttribute('open','');
  await expect(ws.getByTestId('anatomy-stage')).toHaveCount(0);
  await expect(ws.getByTestId('pattern-panel')).toHaveCount(0);
  await expect(ws.locator('.timeline-chart')).toHaveCount(1);
  await expect(ws.getByRole('slider',{name:/Selected sample/})).toHaveCount(1);
  await expect(ws.getByRole('button',{name:/Score & save/})).toHaveCount(1);
  await expect(ws.getByRole('button',{name:/Download saved result|Download research summary/})).toHaveCount(1);
  const historyBox=await ws.locator('#phase-one-flow').boundingBox(),scoreBox=await ws.locator('#score-step').boundingBox();
  expect(scoreBox!.y).toBeGreaterThan(historyBox!.y+historyBox!.height);
  await expect(ws.getByRole('region',{name:'Connected patient cockpit'})).toBeVisible();
  await page.screenshot({path:'../../docs/screenshots/workspace_simple_desktop.png',fullPage:true});
  await openPatientTwin(page);
  await expect(ws.getByTestId('anatomy-stage')).toHaveAttribute('data-status','ready');
  await expect(page.getByRole('button',{name:/guided tour|Restart tour/i})).toHaveCount(0);
  await expect(ws.getByRole('slider',{name:/Selected sample/})).toHaveCount(1);
  await ws.getByRole('slider',{name:/Selected sample/}).fill('0');
  await expect(ws.getByTestId('anatomy-stage')).toHaveAttribute('data-glucose','112');
  await ws.locator('#patient-twin > summary').click();
  await expect(ws.getByTestId('anatomy-stage')).toHaveCount(0);
  await ws.getByRole('navigation',{name:'Dashboard sections'}).getByRole('link',{name:'Review',exact:true}).click();
  await expect(page).toHaveURL(/#review-section$/);await expect(ws.locator('#review-section')).toBeVisible();
  await page.setViewportSize({width:400,height:900});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'../../docs/screenshots/workspace_simple_mobile.png',fullPage:true});
  await page.reload();await expect(page.getByLabel('Local demo review note')).toBeVisible();
  expect(errors).toEqual([]);
});

test('collapsed demo and history preserve scoring, follow-up, review and version selection',async({page,request})=>{
  test.setTimeout(60000);
  const seeded=await request.post('http://127.0.0.1:18083/api/patients/DEMO-001/refresh');
  expect(seeded.ok()).toBe(true);
  await page.goto('/#workspace');
  const before=await (await request.get('http://127.0.0.1:18083/api/patients/DEMO-001/journal')).json();
  expect(before).toHaveLength(1);
  await page.getByRole('button',{name:/Score & save/}).click();
  await expect(page.locator('.outcome-summary')).toBeVisible();
  const after=await (await request.get('http://127.0.0.1:18083/api/patients/DEMO-001/journal')).json();
  expect(after.length).toBe(before.length+1);
  const frozen=(rows:any[])=>rows.map(({predictionId,snapshot,prediction})=>({predictionId,snapshot,prediction}));
  expect(frozen(after.slice(1))).toEqual(frozen(before));
  await openDisclosure(page,'.demo-controls');
  await page.getByRole('button',{name:'Complete follow-up replay'}).click();
  await expect(page.locator('.outcome-summary')).toContainText('8 of 8');
  await page.getByLabel('Local demo review note').fill('TEST ONLY: reviewed the simplified workflow.');
  await page.getByRole('button',{name:'Mark reviewed',exact:true}).click();
  await expect(page.locator('.review-status')).toHaveText('Reviewed (local demo)');
  await openDisclosure(page,'.review-history-disclosure');
  await expect(page.getByRole('list',{name:'Review history'})).toContainText('simplified workflow');
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download saved result'}).click();expect((await download).suggestedFilename()).toContain('DEMO-001');
  await openDisclosure(page,'.saved-attempts');await page.getByRole('button',{name:/Earlier attempt/}).first().click();
  await expect(page.locator('.journal-detail-heading')).toContainText('Historical saved result');
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Future lab',exact:true}).click();
  await expect(page.locator('[data-destination=future]').getByTestId('anatomy-stage')).toHaveAttribute('data-status','ready');
  await expect(page.getByRole('button',{name:/guided tour|Restart tour/i})).toHaveCount(0);
  await expect(page.locator('[data-destination=future]').getByTestId('pattern-panel')).toBeVisible();
});
